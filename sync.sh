#!/usr/bin/env bash
# rice-sync — copy the live rice from $HOME into this repo, check it for secrets,
# then commit and push to the dev branch. Users update from main, so nothing reaches them
# until a release.
#   sync.sh ["message"]  sync, commit (the message is what `rice update` shows), push to dev
#   sync.sh --dry-run    sync and show the diff, no commit
#   sync.sh --release    run the tests, then publish dev as main
# Machine and user files stay out: hypr/monitors.lua, devices.lua, binds-user.lua, user.lua,
# fish/user.fish, hypr-rice/waybar/config.local.json, hypr-rice/kitty/user.conf, waybar/user.css.
set -euo pipefail

REPO=$(cd "$(dirname "$(readlink -f "$0")")" && pwd)
DST="$REPO/home"
DRY=0
MESSAGE="sync: $(date '+%Y-%m-%d %H:%M')"
case "${1:-}" in
    --dry-run) DRY=1 ;;
    --release)
        cd "$REPO"
        [ "$(git rev-parse --abbrev-ref HEAD)" = dev ] || { echo "релиз делается из ветки dev" >&2; exit 1; }
        [ -z "$(git status --porcelain)" ] || { echo "есть незакоммиченные изменения: сначала sync.sh" >&2; exit 1; }
        git fetch -q origin
        [ "$(git rev-parse HEAD)" = "$(git rev-parse origin/dev)" ] || { echo "dev не отправлен: сначала sync.sh" >&2; exit 1; }
        "$REPO/tests/run.sh" || { echo "тесты не прошли, релиза не будет" >&2; exit 1; }
        git push -q origin dev:main
        echo "Выпущено в main: $(git log -1 --format='%h %s')"
        exit 0 ;;
    "") ;;
    *) MESSAGE=$1 ;;
esac
[ "$(git -C "$REPO" rev-parse --abbrev-ref HEAD)" = dev ] \
    || { echo "коммиты идут в ветку dev: git -C $REPO checkout dev" >&2; exit 1; }

# What makes up the rice, relative to $HOME. Directories are copied whole minus EXCLUDES.
PATHS=(
    .config/hypr
    .config/hypr-rice/waybar/config.base.json
    .config/hypr-rice/waybar/scripts
    .config/quickshell
    .config/hypr-rice/kitty/kitty.conf
    .config/fish
    .config/histui/histuid.toml
    .config/systemd/user/histuid.service
    .config/systemd/user/portal-restart.service
    .config/systemd/user/portal-restart.timer
    .config/systemd/user/cache-trim.service
    .config/systemd/user/cache-trim.timer
    .config/systemd/user/xdg-desktop-portal-hyprland.service.d
    .config/systemd/user/xdg-desktop-portal.service.d
    ".config/Code - OSS/User/settings.json"
    ".config/Code - OSS/User/keybindings.json"
    .config/gtk-3.0/settings.ini
    .config/gtk-4.0/settings.ini
    .icons/default/index.theme
    .local/share/icons/WhiteCat
    .local/bin/changetheme
    .local/bin/theme-picker
    .local/bin/launcher
    .local/bin/shot
    .local/bin/shots-gallery
    .local/bin/power-menu
    .local/bin/help-panel
    .local/bin/notif-panel
    .local/bin/screen-fx
    .local/bin/mouse-sens
    .local/bin/portal-restart
    .local/bin/waybar-start
    .local/bin/settings-panel
    .local/bin/power-mode
    .local/bin/network-panel
    .local/bin/proton-run
    .local/bin/rice-install-package
    .claude/statusline.sh
)

# Generated by themegen/changetheme, machine-specific, or backups.
EXCLUDES=(
    --exclude=.config/hypr/build
    --exclude=.config/hypr/hyprlang-backup
    --exclude=.config/hypr/monitors.lua
    --exclude=.config/hypr/devices.lua
    --exclude=.config/hypr/binds-user.lua
    --exclude=.config/hypr/user.lua
    --exclude=.config/fish/user.fish
    --exclude='*.rice-backup'
    --exclude=.config/hypr/palette.lua
    --exclude=.config/hypr/palette.json
    --exclude=.config/hypr/current-theme
    --exclude=.config/hypr/current-wallpaper
    --exclude=.config/hypr/hyprlock-colors.conf
    --exclude=.config/hypr/theme.lua
    --exclude=.config/hypr/hyprlock.conf
    --exclude=.config/hypr/themes/whitecat-cursor.osk
    --exclude=.config/hypr/.rice-installed  # this machine's install marker
    --exclude='.config/hypr/themes/*/assets/battery-*.svg'  # themegen build draws them, in the user's colours
    --exclude=.config/fish/functions/neohtop-dev.fish
    --exclude=__pycache__
    --exclude='*.bak*'
    --exclude='*.pyc'
)

cd "$HOME"
missing=()
present=()
for p in "${PATHS[@]}"; do
    if [ -e "$p" ]; then present+=("$p"); else missing+=("$p"); fi
done
[ ${#missing[@]} -eq 0 ] || printf 'нет на этой машине, пропускаю: %s\n' "${missing[@]}"

rm -rf "$DST"
mkdir -p "$DST"
tar -cf - "${EXCLUDES[@]}" "${present[@]}" | tar -C "$DST" -xf -

# Absolute paths (waybar CSS needs file:// URLs) become a placeholder the installer fills in.
grep -rIl --null "$HOME" "$DST" | xargs -0 -r sed -i "s|$HOME|__HOME__|g"

# Theme-dependent values: changetheme writes them for whatever theme gets installed, so the repo
# keeps neutral ones instead of the theme that happened to be active at sync time.
code_settings="$DST/.config/Code - OSS/User/settings.json"
if [ -f "$code_settings" ]; then
    jq 'del(."workbench.colorTheme", ."git-graph.graph.colours")' "$code_settings" > "$code_settings.tmp"
    mv "$code_settings.tmp" "$code_settings"
fi
sed -i 's|^ExecStart=/usr/bin/histuid --theme .*|ExecStart=/usr/bin/histuid --theme claude|' \
    "$DST/.config/systemd/user/histuid.service"

# Prebuilt files too big for git (release: in packages/apps.txt) go to the GitHub release "files"
# as <file>-<first 12 characters of its sha256>; the repo keeps their checksums, which is what
# rice checks a download against. A new name per version: users still on the previous one keep
# getting the file their checksums expect.
RELEASE_REPO=larion928/hypr-rice
release_has() {  # release_has ASSET: the release "files" already carries ASSET
    gh release view files -R "$RELEASE_REPO" --json assets --jq '.assets[].name' 2>/dev/null | grep -qxF "$1"
}

publish_release_files() {
    local sums="$REPO/packages/release.sha256" path sha asset upload
    : > "$sums.new"
    for path in $(grep -v '^#' "$REPO/packages/apps.txt" | grep -o 'release:[^ ]*' | cut -d: -f2); do
        if [ ! -f "$HOME/$path" ]; then
            echo "нет на этой машине, оставляю прежний: $path"
            grep -F "  $path" "$sums" >> "$sums.new" || true
            continue
        fi
        sha=$(sha256sum < "$HOME/$path" | cut -d' ' -f1)
        echo "$sha  $path" >> "$sums.new"
        asset="$(basename "$path")-${sha:0:12}"
        release_has "$asset" && continue
        if [ "$DRY" = 1 ]; then
            echo "(--dry-run: не выкладываю $asset)"
            continue
        fi
        gh release view files -R "$RELEASE_REPO" >/dev/null 2>&1 \
            || gh release create files -R "$RELEASE_REPO" --latest=false --title "Собранные файлы" \
                   --notes "Файлы, которые rice скачивает вместо хранения в git; контрольные суммы в packages/release.sha256."
        upload=$(mktemp -d)
        cp "$HOME/$path" "$upload/$asset"
        gh release upload files -R "$RELEASE_REPO" "$upload/$asset"
        rm -rf "$upload"
        echo "выложено: $asset"
    done
    mv "$sums.new" "$sums"
}

publish_release_files

# Refuse to publish anything that looks like a secret.
SECRET_RE='sk-ant-[A-Za-z0-9_-]{10,}|gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,}|BEGIN [A-Z ]*PRIVATE KEY|"(accessToken|refreshToken)"[[:space:]]*:[[:space:]]*"|AKIA[0-9A-Z]{16}'
if hits=$(grep -rIEn "$SECRET_RE" "$REPO" --exclude-dir=.git --exclude=sync.sh); then
    echo "СТОП: похоже на секрет, ничего не отправляю:" >&2
    echo "$hits" >&2
    exit 1
fi
# A file this size is either a mistake or will hit GitHub's 100 MB limit.
if big=$(find "$REPO" -path "$REPO/.git" -prune -o -type f -size +50M -print | grep .); then
    echo "СТОП: слишком большие файлы:" >&2
    echo "$big" >&2
    exit 1
fi

cd "$REPO"
git add -A
if git diff --cached --quiet; then
    echo "Изменений нет."
    exit 0
fi
git diff --cached --stat | tail -n 15
if [ "$DRY" = 1 ]; then
    git reset -q
    echo "(--dry-run: ничего не закоммичено)"
    exit 0
fi
git commit -qm "$MESSAGE"
git push -q origin dev
echo "Отправлено: $(git log -1 --format='%h %s')"
