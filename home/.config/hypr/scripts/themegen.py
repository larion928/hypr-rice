# ---------- colors ----------

def rgb(c):
    c = c.lstrip("#")
    return tuple(int(c[i:i + 2], 16) for i in (0, 2, 4))


def hexc(t):
    return "#" + "".join(f"{max(0, min(255, round(v))):02x}" for v in t)


def mix(a, b, t):
    """t=0 -> a, t=1 -> b."""
    ra, rb = rgb(a), rgb(b)
    return hexc(tuple(x + (y - x) * t for x, y in zip(ra, rb)))


def alpha(c, a):
    return f"{c}{round(a * 255):02x}"


def css_rgba(c, a):
    r, g, b = rgb(c)
    return f"rgba({r}, {g}, {b}, {a})"


# ---------- palettes ----------

def load(name):
    data = json.loads((THEMES / name / "palette.json").read_text())
    data["c"] = data["colors"]
    return data


def all_themes():
    return sorted(p.parent.name for p in THEMES.glob("*/palette.json"))


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        path.unlink()
    path.write_text(text)


# ---------- per-theme outputs ----------

def gen_hypr(t):
    c = t["c"]
    write(HYPR / "palette.lua", f"""-- Палитра темы «{t['name']}». {GENERATED}
return {{
    active   = "{c['accent']}",
    active2  = "{c['accent2']}",
    inactive = "{alpha(c['muted'], 0.67)}",
}}
""")
    # Read by the Quickshell screenshot overlay and anything else that wants the full palette.
    write(HYPR / "palette.json", json.dumps({k: v for k, v in t.items() if k != "c"}, indent=2) + "\n")
    write(HYPR / "current-theme", t["name"] + "\n")


def gen_css_palette(t):
    c = t["c"]
    body = "".join(f"@define-color {k:<8}{v};\n" for k, v in c.items())
    text = f"/* Палитра темы «{t['name']}». {GENERATED} */\n{body}"
    write(HOME / ".config/waybar/wallust-colors.css", text)
    write(HOME / ".config/histui/colors.css", text)


def deep_merge(base, over):
    out = dict(base)
    for k, v in over.items():
        out[k] = deep_merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def gen_waybar(t):
    # Shared modules live in config.base.json; a theme may override parts of it in waybar.json.
    base_path = HOME / ".config/waybar/config.base.json"
    if not base_path.exists():
        return
    cfg = json.loads(base_path.read_text())
    over = THEMES / t["name"] / "waybar.json"
    if over.exists():
        cfg = deep_merge(cfg, json.loads(over.read_text()))
    # Machine-specific bits (outputs in persistent-workspaces, ...), not part of the rice repo.
    local = HOME / ".config/waybar/config.local.json"
    if local.exists():
        # One level deep: a module option given here replaces the shared one as a whole.
        for mod, opts in json.loads(local.read_text()).items():
            cfg[mod] = {**cfg[mod], **opts} if isinstance(opts, dict) and isinstance(cfg.get(mod), dict) else opts
    write(HOME / ".config/waybar/config.json", json.dumps(cfg, indent=4, ensure_ascii=False) + "\n")


def gen_kitty(t):
    c = t["c"]
    bg, fg = c["bg"], c["fg"]
    ansi = [c["bg2"], c["crit"], c["good"], c["warn"], c["accent"], c["accent3"], c["accent2"], fg]
    bright = [c["muted"]] + [mix(x, "#ffffff", 0.22) for x in ansi[1:7]] + [mix(fg, "#ffffff", 0.5)]
    lines = [f"# Тема «{t['name']}». {GENERATED}",
             f"foreground {fg}", f"background {bg}",
             f"cursor {c['accent']}", f"cursor_text_color {bg}",
             f"selection_foreground {fg}", f"selection_background {mix(c['accent'], bg, 0.55)}",
             f"url_color {c['accent2']}",
             f"active_border_color {c['accent']}", f"inactive_border_color {c['muted']}",
             f"active_tab_foreground {bg}", f"active_tab_background {c['accent']}",
             f"inactive_tab_foreground {c['muted']}", f"inactive_tab_background {c['bg2']}",
             f"tab_bar_background {bg}", f"mark1_background {c['accent2']}"]
    lines += [f"color{i} {col}" for i, col in enumerate(ansi + bright)]
    write(HOME / ".config/kitty/theme.conf", "\n".join(lines) + "\n")
    # kitty re-reads its config on SIGUSR1, so open windows pick the colours up at once.
    subprocess.run(["pkill", "-USR1", "-x", "kitty"], check=False)


def gen_hyprlock(t, wallpaper):
    c = t["c"]
    lines = [f"# Палитра темы «{t['name']}». {GENERATED}"]
    for k, v in c.items():
        h = v.lstrip("#")
        # hyprlang cannot append alpha to a variable, so ship the variants themes need.
        lines.append(f"${k} = rgb({h})")
        lines.append(f"${k}_glass = rgba({h}cc)")
        lines.append(f"${k}_soft = rgba({h}55)")
    lines.append(f"$font = {t['font']}")
    lines.append(f"$display_font = {t['display']}")
    lines.append(f"$theme_dir = {THEMES / t['name']}")
    if wallpaper:
        lines.append(f"$wallpaper = {wallpaper}")
    else:
        # hyprlock needs some value; fall back to a screenshot of the current screen.
        lines.append("$wallpaper = screenshot")
    write(HYPR / "hyprlock-colors.conf", "\n".join(lines) + "\n")
    theme_conf = THEMES / t["name"] / "hyprlock.conf"
    link = HYPR / "hyprlock.conf"
    if theme_conf.exists():
        if link.exists() or link.is_symlink():
            link.unlink()
        link.symlink_to(theme_conf)


