def build_battery_icons(themes):
    for t in themes:
        d = THEMES / t["name"] / "assets"
        d.mkdir(parents=True, exist_ok=True)
        for old in d.glob("battery-*.svg"):
            old.unlink()
        for i, frame in enumerate(battery_frames(t)):
            (d / f"battery-{i}.svg").write_text(frame)


def refresh():
    """Theme what appeared since the last theme change (a new Firefox profile, an Obsidian vault);
    run at every Hyprland start."""
    cur = HYPR / "current-theme"
    if not cur.exists():
        return
    t = load(cur.read_text().strip())
    wp = HYPR / "current-wallpaper"
    wallpaper = wp.read_text().strip() if wp.exists() else None
    if wallpaper and not Path(wallpaper).exists():
        wallpaper = None
    gen_obsidian(t)
    gen_vesktop(t)
    gen_firefox(t, wallpaper)
    gen_chromium(t, wallpaper)


def build():
    themes = [load(n) for n in all_themes()]
    build_drift(themes)
    print("vscode:", build_vscode(themes))
    print("neohtop:", build_neohtop(themes))
    print("telegram:", build_telegram(themes))
    build_battery_icons(themes)
    cur = (HYPR / "current-theme")
    if cur.exists():
        gen_drift_active(load(cur.read_text().strip()))


def main(argv):
    if len(argv) >= 2 and argv[0] == "apply":
        wp = None
        if "--wallpaper" in argv:
            wp = argv[argv.index("--wallpaper") + 1] or None
        apply(argv[1], wp)
    elif argv[:1] == ["build"]:
        build()
    elif argv[:1] == ["refresh"]:
        refresh()
    else:
        print(__doc__.strip(), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
