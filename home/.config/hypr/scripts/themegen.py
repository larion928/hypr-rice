        frames = [svg(cup)]
        for i in range(1, 6):
            t = i / 5
            # The second wisp trails the first a little.
            a, b = t, max(0.0, t - 0.2) / 0.8
            op = lambda u: round(math.sin(min(1, u) * math.pi) * 0.95, 2)
            frames.append(svg(cup + steam(8.5, 3 - 4.5 * a, op(a)) + steam(12.5, 3.5 - 4.5 * b, op(b))))
