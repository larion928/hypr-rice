def svg(body, view="0 0 24 24"):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}">{body}</svg>'


def pixel_art(grid, body, eyes):
    rects = []
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch in "XB":
                rects.append(f'<rect x="{x}" y="{y}" width="1.02" height="1.02" fill="{body if ch == "X" else eyes}"/>')
    return svg("".join(rects), "0 -2 12 12")


def sparkle(x, y, r, color):
    # Four-pointed star.
    return (f'<path d="M{x} {y - r} L{x + r * 0.28} {y - r * 0.28} L{x + r} {y} L{x + r * 0.28} {y + r * 0.28} '
            f'L{x} {y + r} L{x - r * 0.28} {y + r * 0.28} L{x - r} {y} L{x - r * 0.28} {y - r * 0.28} Z" fill="{color}"/>')


