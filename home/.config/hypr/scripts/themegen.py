def reload_gtk():
    # GTK3 only rereads the user gtk.css when the theme name changes, so bounce it.
    try:
        cur = subprocess.run(["gsettings", "get", "org.gnome.desktop.interface", "gtk-theme"],
                             capture_output=True, text=True, timeout=5).stdout.strip().strip("'")
        if cur:
            subprocess.run(["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", "Adwaita"], timeout=5)
            subprocess.run(["gsettings", "set", "org.gnome.desktop.interface", "gtk-theme", cur], timeout=5)
        # File chooser dialogs (Code - OSS, browsers, ...) come from this portal; it does not
        # follow the bounce above, so restart it. It is D-Bus activated, nothing is lost.
        subprocess.run(["systemctl", "--user", "try-restart", "xdg-desktop-portal-gtk.service"], timeout=10)
    except (OSError, subprocess.SubprocessError):
        pass


DRIFT_BEGIN = "# >>> hypr themes (themegen.py) >>>"
DRIFT_END = "# <<< hypr themes (themegen.py) <<<"


def drift_path():
    return HOME / ".config/drift/config.toml"


def drift_set_engine_theme(text, name):
    if re.search(r"^\[engine\]", text, re.M) is None:
        return f'[engine]\ntheme = "{name}"\n\n' + text
    engine = re.search(r"^\[engine\][^\[]*", text, re.M)
    section = engine.group(0)
    if re.search(r"^theme\s*=", section, re.M):
        new = re.sub(r'^theme\s*=.*$', f'theme = "{name}"', section, count=1, flags=re.M)
    else:
        new = section.replace("[engine]\n", f'[engine]\ntheme = "{name}"\n', 1)
    return text[:engine.start()] + new + text[engine.end():]


def gen_drift_active(t):
    p = drift_path()
    text = p.read_text() if p.exists() else ""
    write(p, drift_set_engine_theme(text, t["name"]))


def vscode_settings_path():
    return HOME / ".config/Code - OSS/User/settings.json"


def vscode_label(t):
    return f"Hypr {t['label']}"


def gen_vscode_active(t):
    p = vscode_settings_path()
    if not p.exists():
        return
    text = p.read_text()
    label = vscode_label(t)
    c = t["c"]
    # Branch lines in Git Graph follow the palette too.
    graph = [c["accent"], c["accent2"], c["good"], c["warn"], c["accent3"], c["crit"], c["muted"]]
    try:
        data = json.loads(text)
        data["workbench.colorTheme"] = label
        data["git-graph.graph.colours"] = graph
        p.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    except json.JSONDecodeError:
        # settings.json with comments: patch the single key in place.
        if '"workbench.colorTheme"' in text:
            text = re.sub(r'"workbench\.colorTheme"\s*:\s*"[^"]*"',
                          f'"workbench.colorTheme": "{label}"', text, count=1)
        else:
            text = text.replace("{", f'{{\n  "workbench.colorTheme": "{label}",', 1)
        p.write_text(text)


ROOT_HELPER = "/usr/local/bin/hypr-theme-root"


def gen_system(t, wallpaper):
    """Folder colours and the SDDM login screen, through the sudo-allowed root helper."""
    if not Path(ROOT_HELPER).exists():
        return
    ui_path = THEMES / t["name"] / "ui.json"
    ui = json.loads(ui_path.read_text()) if ui_path.exists() else {}
    cmds = []
    folders = ui.get("folders")
    stamp = HOME / ".cache/hypr-theme-folders"
    # papirus-folders takes a few seconds; skip it when the colour does not change.
    if folders and (not stamp.exists() or stamp.read_text().strip() != folders):
        cmds.append(f"sudo -n {ROOT_HELPER} folders {folders} >/dev/null && echo {folders} > {stamp}")
    if wallpaper:
        c = t["c"]
        args = " ".join(shlex.quote(a) for a in (wallpaper, c["accent"], c["bg"], c["fg"], t["display"]))
        cmds.append(f"sudo -n {ROOT_HELPER} sddm {args}")
    if cmds:
        # Detached, so changetheme does not wait for the icon theme to be rewritten.
        subprocess.Popen(["sh", "-c", "; ".join(cmds)], start_new_session=True,
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def offer_telegram_theme(t):
    # AyuGram/Telegram cannot be themed from outside: opening the file shows its preview with
    # an "Apply" button. Only offered when the client is running, so nothing pops up otherwise.
    theme = TELEGRAM_DIR / f"{t['name']}.tdesktop-theme"
    if not theme.exists():
        return
    for binary in ("AyuGram", "Telegram"):
        if subprocess.run(["pgrep", "-x", binary], capture_output=True).returncode == 0:
            subprocess.Popen([binary, "--", str(theme)], start_new_session=True,
                             stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            return


def apply(name, wallpaper=None):
    t = load(name)
    # changetheme reloads Hyprland, which drops any screen shader; keep screen-fx in sync.
    (Path(os.environ.get("XDG_RUNTIME_DIR", "/tmp")) / "screen-fx-on").unlink(missing_ok=True)
    gen_hypr(t)
    gen_css_palette(t)
    gen_waybar(t)
    gen_kitty(t)
    gen_hyprlock(t, wallpaper)
    gen_gtk(t)
    gen_drift_active(t)
    gen_vscode_active(t)
    gen_system(t, wallpaper)
    offer_telegram_theme(t)
    reload_gtk()


# ---------- bundled outputs (all themes) ----------

def build_drift(themes):
    blocks = [DRIFT_BEGIN]
    for t in themes:
        c = t["c"]
        pal = [c["accent"], c["accent2"], c["accent3"], c["good"], c["warn"]]
        dim = [mix(x, c["bg"], 0.7) for x in pal]
        blocks.append(f"[theme.{t['name']}]")
        blocks.append(f'bright  = "{mix(c["fg"], "#ffffff", 0.5)}"')
        blocks.append("palette = [" + ", ".join(f'"{x}"' for x in pal) + "]")
        blocks.append("dim     = [" + ", ".join(f'"{x}"' for x in dim) + "]")
        blocks.append("")
    blocks.append(DRIFT_END)
    p = drift_path()
    text = p.read_text() if p.exists() else ""
    text = re.sub(re.escape(DRIFT_BEGIN) + r".*?" + re.escape(DRIFT_END) + r"\n?", "", text, flags=re.S)
    write(p, text.rstrip("\n") + ("\n\n" if text.strip() else "") + "\n".join(blocks) + "\n")


